namespace {

constexpr int kIconSize = 28;
constexpr int kIconStride = 4;
constexpr int kSlotX = 4;
constexpr int kSlotY = 4;

/* Copia exata de NB_UI_OVERLAY_ICON_MICROFONE_BLOQUEADO_MASK do main. */
constexpr uint8_t kMicBlockedMask[] = {
    0x00, 0x1F, 0x80, 0x00, 0x00, 0x7F, 0xE0, 0x00, 0x00, 0xF0, 0xF0, 0x00,
    0x01, 0xC0, 0x38, 0x00, 0x03, 0x80, 0x1C, 0x00, 0x03, 0x00, 0x0C, 0x00,
    0x07, 0x00, 0x0E, 0x00, 0x06, 0x00, 0x06, 0x00, 0x07, 0xE0, 0x7E, 0x00,
    0x07, 0xF0, 0xFE, 0x00, 0x07, 0x40, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00,
    0x06, 0x00, 0xFE, 0x00, 0x07, 0xE1, 0xFF, 0x80, 0xC7, 0xE3, 0xC3, 0xC0,
    0xC6, 0x07, 0x80, 0xE0, 0xC6, 0x0F, 0xC0, 0x60, 0xE7, 0x0E, 0xE0, 0x70,
    0xE3, 0x8C, 0x70, 0x30, 0x63, 0x8C, 0x38, 0x30, 0x71, 0x8C, 0x1C, 0x30,
    0x38, 0x0C, 0x0E, 0x70, 0x38, 0x0E, 0x07, 0xF0, 0x1E, 0x06, 0x03, 0xE0,
    0x0F, 0x07, 0x03, 0xC0, 0x07, 0xE3, 0xC7, 0xC0, 0x01, 0xF1, 0xFF, 0x00,
    0x00, 0x60, 0x7E, 0x00,
};

/* Mesmo desenho de draw_icon_mask() em ui_overlay_service.cpp (main). */
void draw_icon_mask(LGFX_Sprite &canvas, const uint8_t *mask, int x, int y,
                    uint32_t color)
{
    for (int dy = 0; dy < kIconSize; dy++) {
        const uint8_t *row = &mask[(size_t)dy * (size_t)kIconStride];
        for (int dx = 0; dx < kIconSize; dx++) {
            const uint8_t bit = (uint8_t)(0x80U >> (dx & 0x07U));
            if ((row[dx >> 3] & bit) != 0U) {
                canvas.drawPixel(x + dx, y + dy, color);
            }
        }
    }
}

}  // namespace

void nb_head_status_icons_draw(LGFX_Sprite &canvas, uint32_t icon_bits)
{
    if ((icon_bits & NB_DISPLAY_STATUS_ICON_MIC_BLOCKED) != 0U) {
        draw_icon_mask(canvas, kMicBlockedMask, kSlotX, kSlotY, 0xff3030U);
    }
}
